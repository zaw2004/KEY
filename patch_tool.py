import os
import struct
import sys

# ---------- constants (verified from full disassembly) -----------------------
PATCH_OFFSET = 0x9b32          # file offset of the 8-byte little-endian ID
PATCH_SIZE = 8                 # 8 bytes = one x86-64 immediate operand
ORIGINAL_ID = 8556036826       # hardcoded default in the .so
EXPECTED_PREFIX = bytes([0x49, 0xbc])   # 'movabs %r12, imm64' opcode

SO_NAME = 'sirzipp.cpython-311-x86_64-linux-gnu.so'


def current_id(data):
    return struct.unpack_from('<Q', data, PATCH_OFFSET)[0]


# ═════════════════════ ADMIN ID patch ══════════════════════
def patch_admin(path, new_id):
    with open(path, 'rb') as f:
        data = f.read()
    if len(data) < PATCH_OFFSET + PATCH_SIZE:
        sys.exit(f'[!] File is too small ({len(data)} bytes)')
    cur = current_id(data)
    prefix = data[PATCH_OFFSET - 2: PATCH_OFFSET]
    print(f'[*] Current ID in binary : {cur}')
    print(f'[?] Target file          : {path}')
    print(f'[?] Patch offset         : 0x{PATCH_OFFSET:x}')

    if prefix != EXPECTED_PREFIX:
        sys.exit(f'[!] Unexpected prefix bytes (0x{prefix.hex()}) — '
                 'binary version differs. This tool cannot patch it.')

    if not (0 <= new_id <= 0x7fffffffffffffff):
        sys.exit(f'[!] ID must be a positive integer (got {new_id})')
    if cur == new_id:
        print(f'[+] ID is already {new_id} — no change needed')
        return
    if cur != ORIGINAL_ID:
        print(f'[!] Binary holds an unusual ID ({cur}). Patching anyway — '
              'press Ctrl+C within 2s to abort')
        try:
            import time
            time.sleep(2)
        except KeyboardInterrupt:
            print('\n[~] Aborted.')
            return

    old_bytes = data[PATCH_OFFSET: PATCH_OFFSET + PATCH_SIZE]
    new_bytes = struct.pack('<Q', new_id)
    data = data[:PATCH_OFFSET] + new_bytes + data[PATCH_OFFSET + PATCH_SIZE:]

    backup = path + '.orig'
    if not os.path.exists(backup):
        with open(backup, 'wb') as f:
            f.write(open(path, 'rb').read())
        print(f'[*] Backup saved         : {backup}')

    with open(path, 'wb') as f:
        f.write(data)
    print(f'[+] Patched bytes        : {old_bytes.hex()} -> {new_bytes.hex()}')
    print(f'[+] New admin ID         : {new_id}')
    print('[✓] Done. Restart the bot for the change to take effect')


