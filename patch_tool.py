def make_name_loader(new_name):
    out = os.path.join(os.getcwd(), 'run_patched_bot.py')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(NAME_LOADER_TEMPLATE.format(new_name=new_name))
    try:
        os.chmod(out, 0o755)
    except OSError:
        pass
    print('[+] Name loader created:', out)
    print(f'[+] Username in banner/credit -> @{new_name}')
    print('[✓] Run it with: python3 run_patched_bot.py')


def make_token_loader(token):
    out = os.path.join(os.getcwd(), 'run_patched_bot.py')
    with open(out, 'w', encoding='utf-8') as f:
        f.write(LOADER_TEMPLATE.format(token_repr=token))
    try:
        os.chmod(out, 0o755)
    except OSError:
        pass
    print('[+] Loader created:', out)
    print('[✓] Run it with: python3 run_patched_bot.py')
    print('[!] Admin ID ကို ပြောင်းချင်ရင် patch_tool.py admin <ID> ကို')
    print('    အရင် run ပြီးမှ run_patched_bot.py ကို သုံးပါ')


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        sys.exit(0)

    mode = args[0]
    rest = args[1:]

    if mode == 'admin':
        restore = '--restore' in rest
        check = '--check-only' in rest
        new_id = None
        path_arg = None
        i = 0
        while i < len(rest):
            a = rest[i]
            if a == '--file' and i + 1 < len(rest):
                path_arg = rest[i + 1]
                i += 2
                continue
            if a in ('--restore', '--check-only'):
                i += 1
                continue
            if not a.startswith('-'):
                try:
                    new_id = int(a)
                except ValueError:
                    sys.exit(f'[!] Not a valid ID: {a}')
            i += 1
        path = path_arg or os.path.join(os.getcwd(), SO_NAME)
        if not os.path.exists(path):
            sys.exit(f'[!] File not found: {path}')
        if check:
            print('Current admin ID:', current_id(open(path, 'rb').read()),
                  f'({path})')
            return
        print(f'[?] File to patch        : {path}')
        if restore:
            new_id = ORIGINAL_ID
            print(f'[*] Restoring original ID {ORIGINAL_ID}')
        if new_id is None:
            sys.exit('[!] Missing target ID. Usage: patch_tool.py admin NEW_ID')
        patch_admin(path, new_id)

    elif mode == 'token':
        if not rest or rest[0].startswith('-'):
            sys.exit('[!] Missing token. Usage: patch_tool.py token "TOKEN"')
        token = rest[0]
        if not (token.count(':') == 1 and token.split(':')[0].isdigit()
                and len(token) > 30):
            print('[!] Token format looks unusual but proceeding anyway — '
                  'Telegram bot tokens are like 8960099014:AAGTdr-... '
                  '(30-50 chars, one colon)')
        make_token_loader(token)

    elif mode == 'name':
        # banner/name override loader — Telegram username ကို ပြောင်းပေးတဲ့ loader
        if not rest or rest[0].startswith('-'):
            sys.exit('[!] Missing name. Usage: patch_tool.py name NEW_NAME')
        new_name = rest[0]
        make_name_loader(new_name)

    elif mode == 'check':
        path = rest[0] if rest else os.path.join(
            os.path.dirname(os.path.abspath(__file__)), SO_NAME)
        data = open(path, 'rb').read()
        print('Admin ID:', current_id(data))

    else:
        sys.exit(f'[!] Unknown mode: {mode!r}. '
                 'Use "admin", "token" or "name".\n{__doc__}')


if __name__ == '__main__':
    main()
